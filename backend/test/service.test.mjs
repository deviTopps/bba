import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { openDb } from '../src/db.mjs';
import { createApp } from '../src/app.mjs';
import { passwordHash } from '../src/auth.mjs';
import { servicePages } from '../../src/data/services-catalog.ts';

test('admin authentication, enquiry workflow, posts and consultations', async t => {
  const db=openDb(':memory:');
  db.prepare('INSERT INTO admins VALUES (?,?)').run('admin@example.com',passwordHash('unique-test-password'));
  const server=createApp(db).listen(0,'127.0.0.1');await once(server,'listening');
  t.after(()=>{server.close();db.close();});
  const origin='http://127.0.0.1:'+server.address().port;
  let cookie='';
  async function call(path,method='GET',body,auth=true){return fetch(origin+path,{method,headers:{'Content-Type':'application/json',...(auth?{'X-BBA-Admin':'1',Cookie:cookie}:{})},body:body?JSON.stringify(body):undefined});}
  assert.equal((await call('/api/admin/enquiries')).status,401);
  assert.equal((await call('/api/admin/services')).status,401);
  assert.equal((await call('/api/admin/login','POST',{email:'admin@example.com',password:'unique-test-password'},false)).status,403);
  assert.equal((await call('/api/admin/login','POST',{email:'admin@example.com',password:'wrong'})).status,401);
  const login=await call('/api/admin/login','POST',{email:'admin@example.com',password:'unique-test-password'});
  assert.equal(login.status,200);assert.match(login.headers.get('set-cookie'),/HttpOnly/);assert.match(login.headers.get('set-cookie'),/SameSite=Strict/i);
  cookie=login.headers.get('set-cookie').split(';')[0];
  assert.equal((await call('/api/admin/me')).status,200);
  const services=await (await call('/api/admin/services')).json();
  assert.deepEqual(services.items,servicePages.map(({slug,title,spec})=>({slug,title,subservices:spec?.find(row=>row.label==='Core Services')?.items?.map(item=>item.label)||[]})));
  const intake={name:'Test client',email:'client@example.com',service:'Audit',message:'Please discuss audit requirements.',questionnaire:[{id:'A01',question:'Organisation?',answer:'Example'}]};
  assert.equal((await call('/api/public/enquiries','POST',{...intake,email:'invalid'},false)).status,400);
  const submitted=await call('/api/public/enquiries','POST',{...intake,status:'closed'},false);assert.equal(submitted.status,201);
  const id=(await submitted.json()).id;
  assert.equal((await (await call('/api/admin/enquiries/'+id)).json()).status,'new');
  assert.equal((await call('/api/public/enquiries')).status,404);
  assert.equal((await call('/api/admin/enquiries/'+id,'PATCH',{status:'reviewing',notes:'Assigned to review'})).status,200);
  assert.equal((await call('/api/admin/enquiries/'+id,'PATCH',{status:'invalid'})).status,400);
  const post={title:'A test article',slug:'test-article',excerpt:'An example blog article.',topic:'audit',paragraphs:['Article body.'],status:'draft',publishedAt:'2025-01-01T00:00:00Z'};
  const created=await call('/api/admin/posts','POST',post);assert.equal(created.status,201);const postId=(await created.json()).id;
  assert.equal((await (await call('/api/public/posts')).json()).length,0);
  assert.equal((await call('/api/admin/posts','POST',post)).status,409);
  await call('/api/admin/posts/'+postId,'PATCH',{status:'published',publishedAt:'2099-01-01T00:00:00Z'});
  assert.equal((await (await call('/api/public/posts')).json()).length,0);
  await call('/api/admin/posts/'+postId,'PATCH',{publishedAt:'2025-01-01T00:00:00Z'});
  assert.equal((await (await call('/api/public/posts')).json()).length,1);
  await call('/api/admin/posts/'+postId,'PATCH',{status:'draft'});
  assert.equal((await (await call('/api/public/posts')).json()).length,0);
  const selected=services.items.find(service=>service.subservices.length>=2);
  const consultation=await call('/api/admin/consultations','POST',{...intake,service:selected.title,subservices:selected.subservices.slice(0,2),status:'requested'});assert.equal(consultation.status,201);const consultationId=(await consultation.json()).id;
  assert.deepEqual((await (await call('/api/admin/consultations/'+consultationId)).json()).subservices,selected.subservices.slice(0,2));
  assert.equal((await call('/api/admin/consultations/'+consultationId,'PATCH',{status:'scheduled'})).status,400);
  assert.equal((await call('/api/admin/consultations/'+consultationId,'PATCH',{status:'scheduled',scheduledAt:'2027-01-01T10:00:00Z'})).status,200);
  assert.equal((await call('/api/admin/posts/'+postId,'DELETE')).status,200);
  await call('/api/admin/logout','POST',{});assert.equal((await call('/api/admin/me')).status,401);
});
